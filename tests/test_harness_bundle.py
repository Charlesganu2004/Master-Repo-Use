"""The colleague harness bundle: snapshot hygiene, merge fragments and the installer.

harness/files is generated by harness/export-harness.ps1 from the owner's live
folders and lands in a public repository, so the first group of tests is a second
leak gate that does not trust the exporter. The second group checks the JSON merge
fragments against the OpenCode V2 config shape. The last group runs install.ps1
into a throwaway home under Windows PowerShell 5.1 and checks that a rerun changes
nothing.
"""
